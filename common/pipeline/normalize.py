"""Stage: text normalisation and quality filtering.

Normalisation exists so that two byte sequences a reader would call identical
become identical to the tokenizer as well. Without it the vocabulary wastes
slots on duplicate spellings of the same word and every one of them is trained
on a fraction of the data it deserves.

The Devanagari-specific reason NFC matters here: precomposed nukta letters
(U+0958-U+095F, e.g. क़ ख़ ग़) are on Unicode's composition-exclusion list, so
NFC deterministically decomposes them into base letter + nukta (U+093C). Real
corpora contain both spellings; after NFC they are one.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field

# Zero-width joiner / non-joiner. In Devanagari these control conjunct
# rendering. They are applied inconsistently across sources, are invisible, and
# split otherwise-identical words into different token sequences, so they are
# removed rather than preserved.
ZERO_WIDTH = dict.fromkeys(map(ord, "​‌‍⁠﻿"), None)

# Unicode space variants -> plain space.
_SPACE_RE = re.compile(r"[   -   　]")
# Control characters except newline and tab.
_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_URL_RE = re.compile(r"https?://\S+|www\.\S+")
_EMAIL_RE = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.]+\b")
_QUOTE_MAP = str.maketrans({"“": '"', "”": '"', "‘": "'", "’": "'", "–": "-", "—": "-"})
_MULTI_SPACE_RE = re.compile(r"[ \t]+")
_MULTI_NEWLINE_RE = re.compile(r"\n{3,}")
_DEVANAGARI_RANGE = (0x0900, 0x097F)

# Malformed vowel signs, written as AA + a second matra by some legacy Nepali
# input methods and by OCR. They *render* almost identically to the correct
# single character, so they survive proofreading unnoticed.
#
# Unicode normalisation does NOT repair these: U+094B has no canonical
# decomposition, so <U+093E, U+0947> is simply a different string, not a
# canonically equivalent one. NFC leaves it untouched and the tokenizer then
# treats को and काे as unrelated words -- costly, because को is among the most
# frequent morphemes in Nepali. Hence this explicit repair table.
_MATRA_FIXES = {
    "ाे": "ो",  # AA + E   -> O
    "ाै": "ौ",  # AA + AI  -> AU
    "ाॅ": "ॉ",  # AA + CANDRA E -> CANDRA O
    "ाॆ": "ॊ",  # AA + SHORT E  -> SHORT O
}
_MATRA_FIX_RE = re.compile("|".join(map(re.escape, _MATRA_FIXES)))


def fix_devanagari_matras(text: str) -> str:
    """Repair AA+matra sequences that should be a single vowel sign."""
    return _MATRA_FIX_RE.sub(lambda m: _MATRA_FIXES[m.group(0)], text)


@dataclass
class NormalizeConfig:
    """Thresholds for cleaning and quality filtering.

    Every value is written to the stage's stats file so a run can be
    reproduced from the report alone.
    """

    min_chars: int = 200
    max_chars: int = 500_000
    min_devanagari_ratio: float = 0.60
    max_digit_ratio: float = 0.30
    max_non_letter_ratio: float = 0.60
    min_words: int = 30
    # A document whose lines are mostly repeats of each other is a listing page
    # or a scraper artefact, not prose.
    max_repeated_line_ratio: float = 0.50
    strip_urls: bool = True
    # Lines matching these are removed before the document is judged. Used for
    # per-source boilerplate, e.g. the AI-summary banner some outlets prepend.
    boilerplate_patterns: list[str] = field(
        default_factory=lambda: [
            r"News Summary Generated by",
            r"Editorially reviewed",
            r"^\s*(Advertisement|विज्ञापन)\s*$",
        ]
    )

    def compiled_boilerplate(self) -> list[re.Pattern[str]]:
        return [re.compile(p, re.IGNORECASE) for p in self.boilerplate_patterns]


def normalize_text(text: str, cfg: NormalizeConfig, boilerplate=None) -> str:
    """Apply Unicode and whitespace normalisation, and drop boilerplate lines."""
    # NFC first: everything downstream assumes a single canonical spelling.
    text = unicodedata.normalize("NFC", text)
    # After NFC (which cannot do this itself) and after zero-width removal,
    # since a stray ZWNJ between the two matras would otherwise hide the pair.
    text = text.translate(ZERO_WIDTH)
    text = fix_devanagari_matras(text)
    text = text.translate(_QUOTE_MAP)
    text = _CONTROL_RE.sub("", text)
    text = _SPACE_RE.sub(" ", text)

    if cfg.strip_urls:
        text = _URL_RE.sub(" ", text)
        text = _EMAIL_RE.sub(" ", text)

    patterns = boilerplate if boilerplate is not None else cfg.compiled_boilerplate()
    lines = []
    for line in text.splitlines():
        line = _MULTI_SPACE_RE.sub(" ", line).strip()
        if not line:
            continue
        if any(p.search(line) for p in patterns):
            continue
        lines.append(line)

    text = "\n".join(lines)
    text = _MULTI_NEWLINE_RE.sub("\n\n", text)
    return text.strip()


def _ratios(text: str) -> tuple[float, float, float]:
    """Return (devanagari ratio over letters, digit ratio, non-letter ratio)."""
    letters = 0
    devanagari = 0
    digits = 0
    for char in text:
        category = unicodedata.category(char)
        if category.startswith("L"):
            letters += 1
            if _DEVANAGARI_RANGE[0] <= ord(char) <= _DEVANAGARI_RANGE[1]:
                devanagari += 1
        elif category.startswith("N"):
            digits += 1

    total = len(text) or 1
    return (
        devanagari / letters if letters else 0.0,
        digits / total,
        1.0 - (letters / total),
    )


def quality_verdict(text: str, cfg: NormalizeConfig) -> str | None:
    """Return a drop reason, or None if the document should be kept.

    Returning the *reason* rather than a boolean is what lets the report show
    which filter removed how much, and makes a misconfigured threshold obvious
    instead of silent.
    """
    if len(text) < cfg.min_chars:
        return "too_short"
    if len(text) > cfg.max_chars:
        return "too_long"

    words = text.split()
    if len(words) < cfg.min_words:
        return "too_few_words"

    devanagari_ratio, digit_ratio, non_letter_ratio = _ratios(text)
    if devanagari_ratio < cfg.min_devanagari_ratio:
        return "wrong_script"
    if digit_ratio > cfg.max_digit_ratio:
        return "too_many_digits"
    if non_letter_ratio > cfg.max_non_letter_ratio:
        return "too_much_punctuation"

    lines = [line for line in text.splitlines() if line]
    if len(lines) >= 4:
        unique_ratio = len(set(lines)) / len(lines)
        if 1.0 - unique_ratio > cfg.max_repeated_line_ratio:
            return "repetitive_lines"

    return None
